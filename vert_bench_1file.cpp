typedef uint64_t (*Kern)(Data&,int);
struct Case{const char* name;Kern k;int need;bool mixed;}; // need: 0 none, 3 avx2, 5 avx512
static atomic<int> phase{0}; // 0 wait, 1 warm-up, 2 measure, 3 stop
static void worker(Data* d,const Case* c){
 while(phase.load(memory_order_acquire)==0){}
 uint64_t sum=0,h=12345;
 const Kern k=c->k;
 while(phase.load(memory_order_relaxed)==1){ // warm-up: same work, not counted
  for(int r=0;r<R;r+=8){if(k)sum+=k(*d,r);if(c->mixed||!k)for(int i=0;i<8;++i)h=chunk(h+(uint64_t)i,d->buf);}
 }
 uint64_t rows=0,kt=0,ct=0;
 const auto t0=chrono::steady_clock::now();const uint64_t c0=__rdtsc();
 while(phase.load(memory_order_relaxed)==2){
  if(!k){for(int r=0;r<R;r+=8)for(int i=0;i<8;++i)h=chunk(h+(uint64_t)i,d->buf);}
  else if(!c->mixed){for(int r=0;r<R;r+=8)sum+=k(*d,r);}
  else for(int r=0;r<R;r+=8){
   const uint64_t a=__rdtsc();
   sum+=k(*d,r);
   const uint64_t b=__rdtsc();
   for(int i=0;i<8;++i)h=chunk(h+(uint64_t)i,d->buf);
   const uint64_t e=__rdtsc();
   kt+=b-a;ct+=e-b;
  }
  rows+=R;
 }
 const uint64_t c1=__rdtsc();const auto t1=chrono::steady_clock::now();
 d->rows=rows;d->sum=sum+h;d->ns=chrono::duration<double,nano>(t1-t0).count();d->kticks=(double)kt;d->cticks=(double)ct;d->ticks=(double)(c1-c0);
}
