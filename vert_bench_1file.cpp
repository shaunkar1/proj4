__attribute__((noinline)) static uint64_t chunk(uint64_t h,uint8_t* buf){
 uint64_t a=h,b=h^0x9E3779B97F4A7C15ULL;
 for(int i=0;i<12;++i){
  a^=buf[a&1023];a*=0xBF58476D1CE4E5B9ULL;a^=a>>29;
  b+=buf[b&1023];b*=0x94D049BB133111EBULL;b^=b>>31;
  if(__builtin_expect((a&127)==0,0))buf[(b>>8)&1023]++;
  a+=(uint64_t)i;b-=a>>60;
 }
 return a^b;
}
